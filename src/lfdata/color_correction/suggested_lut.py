"""Generates recommended 3D Look-Up Tables (LUTs) from color analysis results.

This module provides utilities to create and save configured `Lut3D` instances
derived from the luminance assessment and recommendations of video analysis.
The exported `.cube` files can be applied directly in FFmpeg, video editors,
or the Color Correction Editor.

Usage example:
    from lfdata.color_correction.suggested_lut import create_suggested_lut

    lut = create_suggested_lut(recommendations=result.recommendations)
    lut.save_cube('suggested_grade.cube')
"""

from __future__ import annotations

from pathlib import Path

from lfdata.color_correction.color_analysis_types import (
    CorrectionRecommendations,
)
from lfdata.color_correction.lut import Lut3D

DEFAULT_SUGGESTED_LUT_SIZE: int = 33
DEFAULT_SUGGESTED_LUT_TITLE: str = 'Suggested Arena Grade'


def create_suggested_lut(
    recommendations: CorrectionRecommendations,
    lut_size: int = DEFAULT_SUGGESTED_LUT_SIZE,
    title: str = DEFAULT_SUGGESTED_LUT_TITLE,
) -> Lut3D:
    """Builds a configured Lut3D instance based on color recommendations.

    Translates recommended shadows lift, midtone gamma, highlight rolloff,
    brightness offset, and contrast multiplier into an active 3D color cube.

    Args:
        recommendations: Recommended parameters generated by video analysis.
        lut_size: Grid resolution along each dimension (default: 33).
        title: Metadata title embedded in the exported LUT.

    Returns:
        Lut3D: Recomputed 3D LUT instance with suggested adjustments.

    Raises:
        ValueError: If lut_size is less than 2.

    Usage example:
        lut = create_suggested_lut(recommendations=analysis_recs, lut_size=33)
    """
    if lut_size < 2:
        raise ValueError(f'LUT dimension size must be >= 2, got {lut_size}')

    lut = Lut3D(size=lut_size)
    lut.title = title
    lut.shadows = recommendations.recommended_shadow_lift
    lut.gamma = recommendations.recommended_gamma
    lut.highlight_rolloff = recommendations.recommended_highlight_rolloff
    lut.brightness = recommendations.recommended_brightness
    lut.contrast = recommendations.recommended_contrast

    lut.recompute()
    return lut


def save_suggested_lut(
    recommendations: CorrectionRecommendations,
    file_path: str | Path,
    lut_size: int = DEFAULT_SUGGESTED_LUT_SIZE,
    title: str | None = None,
) -> Path:
    """Creates and writes a suggested 3D LUT to an Adobe .cube file.

    Args:
        recommendations: Recommended parameters generated by video analysis.
        file_path: Destination path for the saved .cube file.
        lut_size: Grid resolution along each dimension (default: 33).
        title: Optional metadata title to embed in the .cube file header.

    Returns:
        Path: Path object pointing to the written .cube file.

    Raises:
        ValueError: If lut_size is less than 2.

    Usage example:
        path = save_suggested_lut(
            recommendations=recs,
            file_path='arena.cube',
            lut_size=33,
        )
    """
    path_obj = Path(file_path)
    lut_title = (
        title
        if title is not None
        else f'{DEFAULT_SUGGESTED_LUT_TITLE} - {path_obj.stem}'
    )
    lut = create_suggested_lut(
        recommendations=recommendations,
        lut_size=lut_size,
        title=lut_title,
    )
    lut.save_cube(file_path=path_obj, title=lut_title)
    return path_obj

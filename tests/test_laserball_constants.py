from lfdata.model.gametypes.laserball_constants import (
    LASERBALL_CLEAR_STEAL_SCORE_MULTIPLIER,
    LASERBALL_GOAL_SCORE_MULTIPLIER,
    LASERBALL_NOTABILITY_EXTRA_BLOCKS_THRESHOLD,
    LASERBALL_NOTABILITY_HIGH_HIT_DIFF_MIN,
    LASERBALL_NOTABILITY_MIN_ASSISTS,
    LASERBALL_NOTABILITY_MIN_CLEARS,
    LASERBALL_NOTABILITY_MIN_GOALS,
    LASERBALL_NOTABILITY_MIN_STEALS,
    LASERBALL_STAT_CAP,
)


def test_laserball_constants() -> None:
    assert LASERBALL_GOAL_SCORE_MULTIPLIER == 10000
    assert LASERBALL_CLEAR_STEAL_SCORE_MULTIPLIER == 100
    assert LASERBALL_STAT_CAP == 99
    assert LASERBALL_NOTABILITY_MIN_GOALS == 1
    assert LASERBALL_NOTABILITY_MIN_ASSISTS == 1
    assert LASERBALL_NOTABILITY_MIN_STEALS == 2
    assert LASERBALL_NOTABILITY_HIGH_HIT_DIFF_MIN == 1.4
    assert LASERBALL_NOTABILITY_MIN_CLEARS == 2
    assert LASERBALL_NOTABILITY_EXTRA_BLOCKS_THRESHOLD == 20
